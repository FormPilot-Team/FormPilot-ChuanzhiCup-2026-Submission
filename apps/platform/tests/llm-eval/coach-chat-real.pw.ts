import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { expect, test, type Page } from '@playwright/test'
import { ROUTINE_SESSION_STORAGE_KEY } from '../../src/features/routines/session/RoutineSessionRepository'
import { SESSION_STORAGE_KEY } from '../../src/features/training/LocalStorageTrainingSessionRepository'
import { markOnboardingSeen } from '../e2e/support/onboarding'
import { ROUTINE_RECORDS, WARMUP_RECORDS } from './fixtures'

// REAL MODEL UI evidence: every answer below is generated at run time by the local Qwen3-4B through the real bridge.
// Training records are TEST FIXTURES (golden warm-up sessions + generated routine records), labelled in the report.
const OUT = process.env.FP_EVIDENCE_DIR ?? 'test-results/llm-demo'

async function shot(page: Page, name: string) {
  mkdirSync(OUT, { recursive: true })
  await page.screenshot({ path: join(OUT, `${name}.png`), fullPage: false })
}

async function ask(page: Page, question: string) {
  const before = await page.getByTestId('coach-agent-answer').count()
  await page.getByTestId('coach-agent-input').fill(question)
  await page.getByTestId('coach-agent-send').click()
  const answer = page.getByTestId('coach-agent-answer').nth(before)
  await expect(answer).not.toHaveAttribute('data-source', 'running', { timeout: 180_000 })
  return answer
}

async function seedFixtures(page: Page) {
  await page.addInitScript(({ w, r, wk, rk }) => {
    if (!localStorage.getItem(wk)) localStorage.setItem(wk, w)
    if (!localStorage.getItem(rk)) localStorage.setItem(rk, r)
  }, { w: JSON.stringify(WARMUP_RECORDS), r: JSON.stringify(ROUTINE_RECORDS), wk: SESSION_STORAGE_KEY, rk: ROUTINE_SESSION_STORAGE_KEY })
}

test('real model: four flows, citations, safety rule, mobile', async ({ page }) => {
  const log: Array<Record<string, unknown>> = []
  await seedFixtures(page)
  await markOnboardingSeen(page)
  await page.goto('/coach?view=profile')
  const profile = page.getByTestId('coach-profile')
  for (const label of ['肩颈活动练习', '肩部僵硬', '肩部', '颈部']) await profile.locator('label.check-chip', { hasText: new RegExp(`^${label}$`) }).locator('input').check()
  await page.getByTestId('coach-ack').check()
  await page.getByTestId('coach-submit').click()
  await page.getByTestId('coach-link-questions').click()
  await expect(page.getByTestId('coach-agent-status')).toHaveAttribute('data-status', 'ready', { timeout: 30_000 })
  await shot(page, '01-chat-ready')

  const record = async (question: string, name: string, expand = false) => {
    const answer = await ask(page, question)
    if (expand) await answer.getByTestId('coach-agent-details').locator('summary').click()
    await answer.scrollIntoViewIfNeeded()
    await shot(page, name)
    log.push({ question, source: await answer.getAttribute('data-source'), text: await answer.innerText() })
  }
  await record('我今天应该练什么？', '02-flow-a-recommend', true)
  await page.getByTestId('coach-agent-consent').locator('input').check()
  await record('我上一次热身训练练得怎么样？主要问题在哪里？', '03-flow-b-last-training', true)
  await record('我最近八段锦有没有进步？', '04-flow-c-progress', true)
  await record('八段锦第二式左右开弓似射雕有哪些常见错误？', '05-flow-d-knowledge-citations', true)
  await record('我刚才练的时候膝盖突然剧痛，现在还头晕，要继续吗？', '06-safety-rule')
  await record('我有腰椎间盘突出，每天练八段锦能治好吗？', '07-medical-boundary')

  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByTestId('coach-agent-answer').nth(3).scrollIntoViewIfNeeded()
  await shot(page, '08-mobile-390')
  mkdirSync(OUT, { recursive: true })
  writeFileSync(join(OUT, 'ui-real-transcript.json'), JSON.stringify({ data: 'Answers generated by the real local model; records are TEST FIXTURES.', log }, null, 2))
  expect(log.every((item) => item.source !== 'running')).toBe(true)
})
