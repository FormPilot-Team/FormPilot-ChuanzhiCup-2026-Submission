import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { mapRoutineSession, validateRoutineRecord } from '../src/features/coachAgent/routineReader'
import { ReaderFault } from '../src/features/coachAgent/readerTypes'
import { validateTrainingSessionSummary } from '../src/features/coachAgent/validation'
import { createRoutineAnalyzer } from '../src/features/routines/analyzers/registry'
import type { FollowAlongMatch } from '../src/features/routines/followAlong/matcher'
import { getRoutineProgram } from '../src/features/routines/programs'
import { RoutineProgressRecorder } from '../src/features/routines/session/RoutineProgressRecorder'
import type { RoutineSessionRecord } from '../src/features/routines/session/types'
import type { RoutineId, RoutineScope } from '../src/features/routines/types'
import { routineMeasuredCriteria } from '../src/features/scoring/criteria'
import type { RoutineTechniqueRecord } from '../src/features/scoring/routine/techniqueRecord'
import { SCORING_VERSION } from '../src/features/scoring/types'

const START = Date.UTC(2026, 9, 1, 8)
const CAPTURED = START + 1_200_000
const ROUTINES: RoutineId[] = ['baduanjin', 'taijiquan', 'wuqinxi', 'yijinjing']

/** Generated by the actual recorder shape, with explicitly synthetic observations; no user records. */
function record(programId: RoutineId = 'baduanjin', samples = 20): RoutineSessionRecord {
  const program = getRoutineProgram(programId)
  const recorder = new RoutineProgressRecorder(program, { kind: 'full' })
  recorder.markPlayback(0, program.video.durationSeconds, program.video.durationSeconds + 1)
  for (const chapter of program.chapters) {
    const videoTime = (chapter.startSeconds + chapter.endSeconds) / 2
    const match: FollowAlongMatch = { status: 'in_sync', similarity: 0.8, timingOffsetMs: 0,
      matchedAt: videoTime, videoTime, regionScores: { arms: 0.8, torso: 0.8, legs: 0.8 }, mirrored: false }
    for (let index = 0; index < samples; index += 1) recorder.recordComparison(videoTime, match)
  }
  const criterion = routineMeasuredCriteria(programId)[0]
  const chapter = program.chapters.find(item => criterion.exercise === '*' || item.id === criterion.exercise)!
  return {
    schemaVersion: 1, kind: 'routine', id: `${programId}-fixture`, programId, programVersion: program.version,
    scope: { kind: 'full' }, source: 'synthetic', mode: 'normal', matcher: { available: true, version: 'follow-along-v1' },
    startedAt: START, endedAt: START + 1_000_000, activeMs: 900_000, outcome: 'completed', chapters: recorder.snapshot(),
    technique: { version: SCORING_VERSION, criteria: [{ criterionId: criterion.id, chapterId: chapter.id,
      windows: [{ start: chapter.startSeconds + 1, end: chapter.startSeconds + 2, samples: 5, value: 123, score: 41 }] }] },
  }
}

function fault(action: () => unknown, code = 'CORRUPT'): void {
  try { action(); expect.fail('Expected reader failure') } catch (error) {
    expect(error).toBeInstanceOf(ReaderFault)
    expect((error as ReaderFault).code).toBe(code)
  }
}

describe('routine coach reader', () => {
  it.each(ROUTINES)('reads complete saved %s baseline observations without replaying or rescoring', programId => {
    const baselineText = readFileSync(new URL(`./fixtures/routine-baseline/${programId}.json`, import.meta.url), 'utf8')
    const [baseline] = JSON.parse(baselineText) as Array<{ variant: string; scope: RoutineScope;
      record: Pick<RoutineSessionRecord, 'chapters'> & { technique: RoutineTechniqueRecord } }>
    expect(baseline.variant).toBe('identity')
    const saved: RoutineSessionRecord = { ...record(programId), scope: baseline.scope,
      chapters: baseline.record.chapters, technique: baseline.record.technique, source: 'synthetic' }
    const before = structuredClone(saved)
    const mapped = mapRoutineSession(saved, CAPTURED)
    const expectedWindows = baseline.record.technique.criteria.flatMap((criterion, criterionIndex) => criterion.windows.map((window, windowIndex) => ({
      criterionId: criterion.criterionId, chapterId: criterion.chapterId, start: window.start, end: window.end,
      samples: window.samples, value: window.value, score: window.score,
      path: `$.technique.criteria[${criterionIndex}].windows[${windowIndex}]`,
    })))
    const technique = mapped.summary.evidence.filter(item => item.score.scoreKind === 'routine-technique')
    expect(technique).toHaveLength(expectedWindows.length)
    expect(mapped.summary.evidence).toHaveLength(saved.chapters.length + expectedWindows.length)
    technique.forEach((item, index) => {
      const expected = expectedWindows[index]
      expect(item.criterionIds).toEqual([expected.criterionId])
      expect(item.window.start).toMatchObject({ domain: 'video-seconds', value: expected.start })
      expect(item.window.end).toMatchObject({ domain: 'video-seconds', value: expected.end })
      expect(item.quality.sampleCount).toBe(expected.samples)
      expect(item.score.value).toBe(expected.score)
      const detail = mapped.details.find(entry => entry.evidenceId === item.id)!
      expect(detail.recordPaths).toContain(expected.path)
      expect(detail.explanation).toMatchObject({ chapterId: expected.chapterId, samples: expected.samples,
        observedValue: expected.value, savedScore: expected.score })
    })
    const similarity = mapped.summary.evidence.filter(item => item.score.scoreKind === 'follow-along-similarity')
    expect(similarity.map(item => item.quality.sampleCount)).toEqual(saved.chapters.map(chapter => chapter.samples))
    expect(mapped.summary.provenance.source).toBe('synthetic')
    expect(mapped.limitations).toContain('NOT_ELIGIBLE_FOR_HUMAN_PROGRESS_CLAIMS')
    expect(saved).toEqual(before)
    expect(readFileSync(new URL(`./fixtures/routine-baseline/${programId}.json`, import.meta.url), 'utf8')).toBe(baselineText)
  })

  it.each(ROUTINES)('maps %s using saved technique scores and the existing chapter report', programId => {
    const saved = record(programId)
    const mapped = mapRoutineSession(saved, CAPTURED)
    expect(validateTrainingSessionSummary(mapped.summary).ok).toBe(true)
    expect(mapped.summary).toMatchObject({ sessionId: saved.id, kind: 'routine', status: 'completed',
      completedReps: null, activeDurationMs: 900_000, recordRef: { id: saved.id, version: '1' },
      provenance: { source: 'synthetic', mode: 'normal', producer: 'repository' } })
    const technique = mapped.summary.evidence.find(item => item.score.scoreKind === 'routine-technique')!
    expect(technique.score).toMatchObject({ scoreKind: 'routine-technique', value: 41, scoringVersion: SCORING_VERSION, rulesVersion: null })
    expect(technique.window).toMatchObject({ start: { domain: 'video-seconds', clockId: `${programId}@1.0.0` },
      end: { domain: 'video-seconds', clockId: `${programId}@1.0.0` } })
    expect(mapped.summary.evidence.filter(item => item.score.scoreKind === 'follow-along-similarity')
      .every(item => item.score.value === 0.8)).toBe(true)
    expect(mapped.metadata.rhythm).toEqual({ syncShare: 100, tempo: null })
    expect(mapped.details).toHaveLength(mapped.summary.evidence.length)
    expect(new Set(mapped.details.map(item => item.evidenceId))).toEqual(new Set(mapped.summary.evidence.map(item => item.id)))
    expect(mapped.limitations).toContain('NOT_ELIGIBLE_FOR_HUMAN_PROGRESS_CLAIMS')
  })

  it('retains proven live and fast separately, without declaring test data human progress', () => {
    const saved = record()
    saved.source = 'live'
    saved.mode = 'fast'
    const mapped = mapRoutineSession(saved, CAPTURED)
    expect(mapped.summary.provenance).toMatchObject({ source: 'live', mode: 'fast' })
    expect(mapped.limitations).toContain('NOT_ELIGIBLE_FOR_HUMAN_PROGRESS_CLAIMS')
    expect(mapped.summary.evidence.every(item => item.provenance.mode === 'fast')).toBe(true)
  })

  it('keeps missing legacy source and mode unknown without modifying the record', () => {
    const saved = record() as unknown as Record<string, unknown>
    delete saved.source
    delete saved.mode
    const before = structuredClone(saved)
    const mapped = mapRoutineSession(saved, CAPTURED)
    expect(mapped.summary.provenance).toEqual({ source: 'unknown', mode: 'unknown', producer: 'repository' })
    expect(validateRoutineRecord(saved).source).toBeUndefined()
    expect(mapped.limitations).toContain('LEGACY_PROVENANCE_UNKNOWN')
    expect(saved).toEqual(before)
  })

  it('reads active and incomplete records with their original outcome and end semantics', () => {
    const active = record()
    active.outcome = 'in_progress'
    delete active.endedAt
    expect(mapRoutineSession(active, CAPTURED).summary).toMatchObject({ status: 'active', endedAt: null })
    const incomplete = record()
    incomplete.outcome = 'incomplete'
    expect(mapRoutineSession(incomplete, CAPTURED).summary).toMatchObject({ status: 'incomplete', endedAt: { value: incomplete.endedAt } })
  })

  it.each([
    ['session', (saved: RoutineSessionRecord) => { saved.schemaVersion = 99 as 1 }],
    ['program', (saved: RoutineSessionRecord) => { saved.programVersion = '0.9.0' }],
    ['matcher', (saved: RoutineSessionRecord) => { saved.matcher.version = 'follow-along-future' }],
    ['technique', (saved: RoutineSessionRecord) => { saved.technique!.version = 'scoring-future' }],
  ])('rejects unsupported %s version', (_name, mutate) => {
    const saved = record(); mutate(saved)
    fault(() => mapRoutineSession(saved, CAPTURED), 'UNSUPPORTED_VERSION')
  })

  it('validates optional analyzer versions without exposing arbitrary analyzer content', () => {
    const saved = record()
    const analyzer = createRoutineAnalyzer(getRoutineProgram(saved.programId))!
    saved.analysis = { analyzerId: analyzer.id, version: 'unknown-version', chapters: [] }
    fault(() => mapRoutineSession(saved, CAPTURED), 'UNSUPPORTED_VERSION')
    saved.analysis.version = analyzer.version
    const mapped = mapRoutineSession(saved, CAPTURED)
    expect(mapped.metadata).not.toHaveProperty('analysis')
  })

  it.each([101, -1, Number.NaN, Number.POSITIVE_INFINITY])('rejects invalid saved technique score %s', score => {
    const saved = record(); saved.technique!.criteria[0].windows[0].score = score
    fault(() => mapRoutineSession(saved, CAPTURED))
  })

  it('preserves true zero scores and signed pose observations', () => {
    const saved = record(); saved.technique!.criteria[0].windows[0].score = 0
    saved.technique!.criteria[0].windows[0].value = -0.25
    const mapped = mapRoutineSession(saved, CAPTURED)
    expect(mapped.summary.evidence.find(item => item.score.scoreKind === 'routine-technique')!.score).toMatchObject({ status: 'available', value: 0 })
    expect(mapped.details.at(-1)!.explanation).toMatchObject({ observedValue: -0.25, savedScore: 0 })
  })

  it.each(['unknown-criterion', 'warmup.squat.depth', 'tjq.all.torso_upright'])('rejects unresolved or wrong-routine criterion %s', criterionId => {
    const saved = record(); saved.technique!.criteria[0].criterionId = criterionId
    fault(() => mapRoutineSession(saved, CAPTURED))
  })

  it('rejects valid criterion ids attached to a different chapter and duplicate references', () => {
    const saved = record()
    const own = routineMeasuredCriteria('baduanjin').find(item => item.exercise !== '*')!
    saved.technique!.criteria[0].criterionId = own.id
    saved.technique!.criteria[0].chapterId = getRoutineProgram('baduanjin').chapters.find(item => item.id !== own.exercise)!.id
    fault(() => mapRoutineSession(saved, CAPTURED))
    const duplicate = record(); duplicate.technique!.criteria.push(structuredClone(duplicate.technique!.criteria[0]))
    fault(() => mapRoutineSession(duplicate, CAPTURED))
  })

  it.each([
    ['negative sample count', (saved: RoutineSessionRecord) => { saved.chapters[0].samples = -1 }],
    ['fractional sample count', (saved: RoutineSessionRecord) => { saved.chapters[0].samples = 20.5 }],
    ['out of range similarity sum', (saved: RoutineSessionRecord) => { saved.chapters[0].similaritySum = 21 }],
    ['wrong status totals', (saved: RoutineSessionRecord) => { saved.chapters[0].statusCounts.ahead = 1 }],
    ['out of range region sum', (saved: RoutineSessionRecord) => { saved.chapters[0].regionSums.arms = 21 }],
    ['out of range coverage', (saved: RoutineSessionRecord) => { saved.chapters[0].coveredSeconds = saved.chapters[0].totalSeconds + 1 }],
    ['unproven score', (saved: RoutineSessionRecord) => { saved.technique!.criteria[0].windows[0].samples = 4 }],
    ['half null observation', (saved: RoutineSessionRecord) => { saved.technique!.criteria[0].windows[0].value = null }],
    ['missing chapter', (saved: RoutineSessionRecord) => { saved.chapters.pop() }],
    ['duplicate chapter', (saved: RoutineSessionRecord) => { saved.chapters.push(structuredClone(saved.chapters[0])) }],
    ['unknown form', (saved: RoutineSessionRecord) => { saved.scope = { kind: 'form', chapterId: 'absent' } }],
    ['unavailable reference with observations', (saved: RoutineSessionRecord) => { saved.matcher.available = false }],
  ])('rejects inconsistent %s', (_name, mutate) => {
    const saved = record(); mutate(saved)
    fault(() => mapRoutineSession(saved, CAPTURED))
  })

  it.each([
    ['negative epoch', (saved: RoutineSessionRecord) => { saved.startedAt = -1 }],
    ['fractional epoch', (saved: RoutineSessionRecord) => { saved.startedAt = START + 0.5 }],
    ['nonfinite epoch', (saved: RoutineSessionRecord) => { saved.startedAt = Number.NaN }],
    ['reversed epoch', (saved: RoutineSessionRecord) => { saved.endedAt = START - 1 }],
    ['missing end', (saved: RoutineSessionRecord) => { delete saved.endedAt }],
    ['active record with end', (saved: RoutineSessionRecord) => { saved.outcome = 'in_progress' }],
    ['active span overflow', (saved: RoutineSessionRecord) => { saved.activeMs = 1_000_001 }],
    ['epoch in video window', (saved: RoutineSessionRecord) => { saved.technique!.criteria[0].windows[0].start = START }],
    ['reversed video window', (saved: RoutineSessionRecord) => { const window = saved.technique!.criteria[0].windows[0]; window.end = window.start - 1 }],
    ['foreign video chapter', (saved: RoutineSessionRecord) => { saved.technique!.criteria[0].windows[0].end = getRoutineProgram(saved.programId).video.durationSeconds }],
  ])('rejects invalid time: %s', (_name, mutate) => {
    const saved = record(); mutate(saved)
    fault(() => mapRoutineSession(saved, CAPTURED))
  })

  it('does not conflate snapshot epoch with video seconds', () => {
    fault(() => mapRoutineSession(record(), 100))
    fault(() => mapRoutineSession(record(), CAPTURED + 0.5))
  })

  it('keeps missing technique and insufficient observations explicit without zero scores', () => {
    const saved = record('baduanjin', 0)
    delete saved.technique
    saved.matcher.available = false
    const mapped = mapRoutineSession(saved, CAPTURED)
    expect(mapped.summary.evidence.every(item => item.score.value === null && item.score.status === 'insufficient')).toBe(true)
    expect(mapped.limitations).toContain('NO_SAVED_TECHNIQUE_EVIDENCE')
    expect(mapped.limitations).toContain('REFERENCE_TRACK_UNAVAILABLE')
    expect(mapped.metadata.technique).toMatchObject({ available: false, score: null })
  })

  it('keeps unobserved guidance references distinct from saved scoring evidence', () => {
    const mapped = mapRoutineSession(record(), CAPTURED)
    const references = mapped.metadata.guidanceReferences as Record<string, unknown>[]
    expect(references.length).toBeGreaterThan(0)
    expect(references.every(item => item.scoreKind === 'guidance' && item.value === null && item.observed === false)).toBe(true)
    expect(mapped.summary.evidence.every(item => item.score.scoreKind !== 'warmup-standard')).toBe(true)
    const explanation = mapped.details.at(-1)!.explanation as Record<string, unknown>
    expect(explanation.sourceType).toBeDefined()
    expect(explanation.thresholdSource).toBe('FORMPILOT_CALIBRATED')
    expect(explanation.thresholdBasis).toEqual(expect.any(String))
  })

  it('is deterministic and leaves deep-frozen original storage values unchanged', () => {
    const saved = record()
    const before = JSON.stringify(saved)
    const freeze = (value: unknown): void => {
      if (value && typeof value === 'object') { Object.values(value).forEach(freeze); Object.freeze(value) }
    }
    freeze(saved)
    const first = mapRoutineSession(saved, CAPTURED)
    expect(mapRoutineSession(saved, CAPTURED)).toEqual(first)
    expect(JSON.stringify(saved)).toBe(before)
    first.summary.evidence[0].quality.sampleCount = 0
    expect(saved.chapters[0].samples).toBe(20)
  })

  it('preserves 128-character session IDs with bounded, distinct and stable evidence references', () => {
    const saved = record()
    saved.id = 'a'.repeat(128)
    const mapped = mapRoutineSession(saved, CAPTURED)
    expect(mapped.summary.id).toBe(saved.id)
    expect(mapped.summary.sessionId).toBe(saved.id)
    expect(mapped.summary.recordRef.id).toBe(saved.id)
    const ids = mapped.summary.evidence.map(item => item.id)
    expect(new Set(ids).size).toBe(ids.length)
    expect(ids.every(id => id.length <= 128)).toBe(true)
    expect(mapped.summary.evidence.every(item => item.recordRef.id === saved.id)).toBe(true)
    expect(mapRoutineSession(saved, CAPTURED).summary.evidence.map(item => item.id)).toEqual(ids)
    const other = { ...saved, id: `${'a'.repeat(127)}b` }
    expect(mapRoutineSession(other, CAPTURED).summary.evidence.some(item => ids.includes(item.id))).toBe(false)
  })

  it.each(['duplicate', 'overlapping', 'out-of-order'])('rejects %s phase windows for one criterion', kind => {
    const saved = record()
    const first = saved.technique!.criteria[0].windows[0]
    const next = { ...first }
    if (kind === 'overlapping') { next.start += 0.5; next.end += 0.5 }
    if (kind === 'out-of-order') { next.start -= 0.5; next.end -= 0.5 }
    saved.technique!.criteria[0].windows.push(next)
    fault(() => mapRoutineSession(saved, CAPTURED))
  })

  it('accepts adjacent split phase windows without adding their sample counts together', () => {
    const saved = record()
    const first = saved.technique!.criteria[0].windows[0]
    saved.technique!.criteria[0].windows.push({ ...first, start: first.end, end: first.end + 1, score: 72 })
    const mapped = mapRoutineSession(saved, CAPTURED)
    const windows = mapped.summary.evidence.filter(item => item.score.scoreKind === 'routine-technique')
    expect(windows.map(item => item.quality.sampleCount)).toEqual([5, 5])
    expect(windows.map(item => item.score.value)).toEqual([41, 72])
    expect(mapped.limitations).toContain('TECHNIQUE_SAMPLE_COUNTS_ARE_PER_WINDOW_NOT_DISTINCT_SESSION_SAMPLES')
  })

  it('projects only allowlisted values and discards raw media, landmarks and arbitrary payloads', () => {
    const saved = { ...record(), landmarks: [{ privateValue: 'PRIVATE_POSE_PAYLOAD' }], videoFile: 'PRIVATE_VIDEO_PATH', custom: 'PRIVATE_ARBITRARY_DATA' }
    const result = JSON.stringify(mapRoutineSession(saved, CAPTURED))
    expect(result).not.toContain('PRIVATE_')
    expect(result).not.toContain('landmarks')
    expect(result).not.toContain('videoFile')
  })
})
