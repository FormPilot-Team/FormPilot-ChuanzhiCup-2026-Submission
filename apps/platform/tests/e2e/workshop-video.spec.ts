import { expect, test } from '@playwright/test'
import { CUSTOM_ACTION_STORAGE_KEY } from '../../src/features/workshop/types'
import { markOnboardingSeen } from './support/onboarding'

test('local demonstration video is previewed without being saved as an action file', async ({ page }) => {
  await markOnboardingSeen(page)
  await page.goto('/workshop/new')
  await page.getByLabel('动作名称').fill('视频示范测试')
  await page.getByTestId('editor-next').click()
  await page.getByTestId('method-video').click()
  await expect(page.getByTestId('camera-panel')).toBeHidden()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  const input = page.getByTestId('workshop-video-input')
  await input.setInputFiles('public/assets/demos/lateral-raise.mp4')
  const preview = page.getByTestId('workshop-video-preview')
  await expect(preview).toBeVisible()
  await expect(page.getByText('可以播放视频并拖动到想要记录的姿势。')).toBeVisible()
  await expect(page.getByRole('button', { name: '记录当前片段为开始姿势' })).toBeEnabled()
  await page.getByRole('button', { name: '记录当前片段为开始姿势' }).click()
  await expect(page.getByTestId('pose-card-start')).toHaveAttribute('data-recorded', 'true', { timeout: 30_000 })
  await preview.evaluate(async (video: HTMLVideoElement) => {
    await new Promise<void>((resolve) => {
      video.addEventListener('seeked', () => resolve(), { once: true })
      video.currentTime = 2
    })
  })
  await page.getByRole('button', { name: '记录当前片段为完成姿势' }).click()
  await expect(page.getByTestId('pose-card-finish')).toHaveAttribute('data-recorded', 'true', { timeout: 30_000 })
  await expect(page.getByTestId('calibration-summary')).toContainText('已记录开始和完成姿势')
  await input.setInputFiles({ name: 'broken.mov', mimeType: 'video/quicktime', buffer: Buffer.from('not a video') })
  await expect(page.getByRole('alert')).toContainText('当前设备无法播放这个视频')
  await page.getByRole('button', { name: '改用摄像头示范' }).click()
  await expect(page.getByTestId('camera-panel')).toBeVisible()
  await expect(page.getByTestId('pose-card-start')).toHaveAttribute('data-recorded', 'true')
  await expect(page.getByTestId('pose-card-finish')).toHaveAttribute('data-recorded', 'true')
  await page.getByTestId('editor-next').click()
  await page.getByTestId('editor-next').click()
  await page.getByTestId('editor-save').click()
  const stored = await page.evaluate((key) => localStorage.getItem(key), CUSTOM_ACTION_STORAGE_KEY)
  expect(stored).toContain('视频示范测试')
  expect(stored).not.toMatch(/lateral-raise\.mp4|blob:|data:video/)
})

test('continuous demonstration proposes a reviewable template from local video', async ({ page }) => {
  test.setTimeout(120_000)
  await markOnboardingSeen(page)
  await page.goto('/workshop/new')
  await page.getByLabel('动作名称').fill('连续示范测试')
  await page.getByTestId('editor-next').click()
  await page.getByTestId('method-video').click()
  await page.getByTestId('workshop-video-input').setInputFiles('public/assets/demos/lateral-raise.mp4')
  await expect(page.getByRole('button', { name: '分析这段连续示范' })).toBeEnabled()
  await page.getByTestId('workshop-continuous-scan').click()
  const proposal = page.getByTestId('workshop-continuous-suggestion')
  await expect(proposal).toContainText('找到阶段', { timeout: 90_000 })
  await expect(page.getByTestId('pose-card-start')).toHaveAttribute('data-recorded', 'false')
  await proposal.getByRole('button', { name: '采用这组建议' }).click()
  await expect(page.getByTestId('pose-card-start')).toHaveAttribute('data-recorded', 'true')
  await expect(page.getByTestId('pose-card-finish')).toHaveAttribute('data-recorded', 'true')
  await page.getByTestId('editor-next').click()
  await expect(page.getByTestId('editor-step')).toHaveAttribute('data-step', 'test')
  await page.getByTestId('editor-next').click()
  await page.getByTestId('editor-save').click()
  const stored = await page.evaluate((key) => localStorage.getItem(key), CUSTOM_ACTION_STORAGE_KEY)
  expect(stored).toContain('连续示范测试')
  expect(stored).not.toMatch(/lateral-raise\.mp4|blob:|data:video/)
})
